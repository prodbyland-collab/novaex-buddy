export function translateMessage(message, lang = "en") {
  const text = String(message ?? "");
  if (lang !== "ka" || !text || /[\u10a0-\u10ff]/.test(text)) return text;
  if (georgianUi[text]) return georgianUi[text];
  for (const [source, translation] of Object.entries(georgianUi)) {
    if (!source.includes("{")) continue;
    const names = [];
    const escaped = source.replace(/[.*+?^$()|[\]\\]/g, "\\$&").replace(/\{(\w+)\}/g, (_, name) => {
      names.push(name);
      return "(.+?)";
    });
    const match = text.match(new RegExp(`^${escaped}$`));
    if (match)
      return names.reduce(
        (out, name, index) => out.replaceAll(`{${name}}`, match[index + 1]),
        translation,
      );
  }
  return georgianUi["Something went wrong. Please try again."];
}
